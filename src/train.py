import math

def plot_categorical_distributions(
    df, categoric_cols, n_cols=2, color="#4c72b0"
):
    """Plot compact horizontal countplots with vertical grid lines for all categories in the specified columns."""
    n_items = len(categoric_cols)
    if n_items == 0:
        print("No categorical columns provided to plot.")
        return

    # Calculate grid dimensions
    n_rows = math.ceil(n_items / n_cols)

    # Compact figure size (5.5 x 2.2 per subplot) + squeeze=False for safe indexing
    fig, axes = plt.subplots(
        n_rows, n_cols, figsize=(5.5 * n_cols, 2.2 * n_rows), squeeze=False
    )
    axes = axes.flatten()

    # 'whitegrid' theme enables faint grid lines automatically
    sns.set_theme(style="whitegrid", font_scale=0.9)

    for i, col in enumerate(categoric_cols):
        ax = axes[i]

        # Clean fillna without triggering deprecation warnings
        temp_series = df[col].fillna("Missing").astype(str)

        # Get full category order sorted by frequency
        order = temp_series.value_counts().index

        # Horizontal countplot using the exact steel blue color (#4c72b0)
        sns.countplot(
            y=temp_series,
            order=order,
            color=color,
            ax=ax,
        )

        # Value labels on bars
        ax.bar_label(ax.containers[0], padding=3, fontsize=8)

        # Ensure vertical grid lines are enabled while removing horizontal ones for cleanliness
        ax.grid(True, axis="x", linestyle="--", alpha=0.7)
        ax.grid(False, axis="y")

        # Title & axis label formatting
        ax.set_title(f"Distribution of '{col}'", fontsize=10, pad=6)
        ax.set_xlabel("Count", fontsize=9)
        ax.set_ylabel(col, fontsize=9)
        ax.tick_params(labelsize=8)

    # Delete unused empty subplots
    for j in range(n_items, len(axes)):
        fig.delaxes(axes[j])

    plt.tight_layout()
    plt.show()

# plot multiple categorical columns distribution

